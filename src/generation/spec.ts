import { SignalRMethodType, type SignalRClientMethod } from "./hbs-helpers.ts";

type Hub = { hubName: string; hubContract: { methods: SignalRClientMethod[] } };
export type Spec = { hubs: Record<string, Hub>; dtos: Record<string, unknown> };

function invalid(path: string, expected: string): never {
  throw new Error(
    `Invalid SignalSpec at ${path}: expected ${expected}. The JSON may have been generated by an incompatible SignalSpec version, or may not be a SignalSpec document.`,
  );
}

function record(value: unknown, path: string): Record<string, unknown> {
  if (!value || typeof value !== "object" || Array.isArray(value)) invalid(path, "an object");
  return value as Record<string, unknown>;
}

function text(value: unknown, path: string) {
  if (typeof value !== "string" || !value.trim()) invalid(path, "a non-empty string");
}

function array(value: unknown, path: string): unknown[] {
  if (!Array.isArray(value)) invalid(path, "an array");
  return value;
}

function properties(value: unknown, path: string) {
  for (const [index, entry] of array(value, path).entries()) {
    const itemPath = `${path}[${index}]`;
    const item = record(entry, itemPath);
    text(item.name, `${itemPath}.name`);
    text(item.type, `${itemPath}.type`);
  }
}

export function validateSpec(value: unknown): asserts value is Spec {
  const spec = record(value, "$");
  const hubs = record(spec.hubs, "$.hubs");
  const dtos = record(spec.dtos, "$.dtos");
  for (const [name, value] of Object.entries(dtos)) {
    const path = `$.dtos[${JSON.stringify(name)}]`;
    properties(record(value, path).properties, `${path}.properties`);
  }
  for (const [name, value] of Object.entries(hubs)) {
    const path = `$.hubs[${JSON.stringify(name)}]`;
    const hub = record(value, path);
    text(hub.hubName, `${path}.hubName`);
    const contract = record(hub.hubContract, `${path}.hubContract`);
    for (const [index, value] of array(contract.methods, `${path}.hubContract.methods`).entries()) {
      const methodPath = `${path}.hubContract.methods[${index}]`;
      const method = record(value, methodPath);
      text(method.name, `${methodPath}.name`);
      if (!Object.values(SignalRMethodType).includes(method.methodType as SignalRMethodType))
        invalid(`${methodPath}.methodType`, "default, frontendMethod, or backendMethod");
      if (method.parameters !== undefined)
        properties(method.parameters, `${methodPath}.parameters`);
      if (method.returns !== undefined && method.returns !== null)
        text(method.returns, `${methodPath}.returns`);
    }
  }
}

export function dtoImports(hub: Hub, dtos: Spec["dtos"]): string[] {
  const names = new Set(Object.keys(dtos));
  const imports = new Set<string>();
  for (const method of hub.hubContract.methods) {
    for (const type of [
      ...(method.parameters ?? []).map((parameter) => parameter.type),
      method.returns ?? "",
    ]) {
      for (const identifier of type.match(/[A-Za-z_$][\w$]*/g) ?? []) {
        if (names.has(identifier)) imports.add(identifier);
      }
    }
  }
  return [...imports].sort();
}
